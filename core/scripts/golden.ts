// One case per line keeps the files small and their diffs readable.
function write(path: string, data: Record<string, unknown>) {
  const fields = Object.entries(data).map(([key, value]) => {
    const body = Array.isArray(value)
      ? `[\n${value.map((item) => JSON.stringify(item)).join(",\n")}\n]`
      : JSON.stringify(value);
    return `${JSON.stringify(key)}: ${body}`;
  });
  writeFileSync(join(root, path), `{\n${fields.join(",\n")}\n}\n`);
}

// A small seeded generator (mulberry32), so every run writes the same files.
function random(seed: number) {
  let a = seed;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

function fuzz(seed: number, n: number, pools: string[], maxLength: number): string[] {
  const next = random(seed);
  const chars = pools.map((pool) => Array.from(pool));
  const out: string[] = [];
  for (let i = 0; i < n; i++) {
    let s = "";
    const length = 1 + Math.floor(next() * maxLength);
    for (let j = 0; j < length; j++) {
      const pool = chars[Math.floor(next() * chars.length)] ?? [];
      s += pool[Math.floor(next() * pool.length)] ?? "";
    }
    out.push(s);
  }
  return out;
}

const run = (from: number, to: number) =>
  String.fromCodePoint(...Array.from({ length: to - from + 1 }, (_, i) => from + i));

// --- The Unicode 16 classes the o200k split pattern uses ------------------------------------

async function classes() {
  const data = await import(join(tokenizerDir, "esm/encodingParams/unicode16Data.js"));
  const ranges = (source: string): [number, number][] => {
    const out: [number, number][] = [];
    const one = String.raw`\\u(?:\{([0-9A-Fa-f]+)\}|([0-9A-Fa-f]{4}))`;
    const re = new RegExp(`${one}(?:-${one})?`, "g");
    for (const m of source.matchAll(re)) {
      const from = Number.parseInt(m[1] ?? m[2] ?? "", 16);
      const to = m[3] || m[4] ? Number.parseInt(m[3] ?? m[4] ?? "", 16) : from;
      out.push([from, to]);
    }
    return out;
  };
  const tables = [
    ["letters", data.UNICODE_16_LETTER_RANGES, "\\p{L}"],
    ["numbers", data.UNICODE_16_NUMBER_RANGES, "\\p{N}"],
    ["upper", data.UNICODE_16_O200K_UPPER_RANGES, "\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}"],
    ["lower", data.UNICODE_16_O200K_LOWER_RANGES, "\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}"],
  ] as const;
  const lines = [
    "// Code generated by core/scripts/golden.ts from gpt-tokenizer 4.1.1; DO NOT EDIT.",
    "",
    "package o200k",
    "",
    "// The character classes of the o200k split pattern as Unicode 16 defines them, which is what",
    "// tiktoken and gpt-tokenizer use. Go's own tables are an older Unicode, so they are not used.",
    "const (",
  ];
  for (const [name, source, meaning] of tables) {
    const body = ranges(source as string)
      .map(([from, to]) =>
        from === to
          ? `\\x{${from.toString(16)}}`
          : `\\x{${from.toString(16)}}-\\x{${to.toString(16)}}`,
      )
      .join("");
    lines.push(`\t// ${name} is ${meaning} in Unicode 16.`, `\t${name} = \`${body}\``);
  }
  lines.push(")", "");
  writeFileSync(join(root, "core-go/internal/llm/o200k/classes.go"), lines.join("\n"));
}

